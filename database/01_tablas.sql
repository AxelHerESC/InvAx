BEGIN;

CREATE TABLE IF NOT EXISTS public.productos (
    id_producto TEXT PRIMARY KEY,
    nombre TEXT NOT NULL,
    precio NUMERIC(12, 2) NOT NULL CHECK (precio >= 0),
    cantidad INTEGER NOT NULL CHECK (cantidad >= 0),
    version INTEGER NOT NULL DEFAULT 0 CHECK (version >= 0)
);

CREATE TABLE IF NOT EXISTS public.usuarios (
    usuario TEXT PRIMARY KEY,
    salt TEXT NOT NULL,
    clave_hash TEXT NOT NULL,
    rol TEXT NOT NULL CHECK (rol IN ('vendedor', 'administrador')),
    activo SMALLINT NOT NULL DEFAULT 1 CHECK (activo IN (0, 1)),
    creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.operaciones (
    request_id TEXT PRIMARY KEY,
    accion TEXT NOT NULL,
    usuario TEXT NOT NULL,
    respuesta_json TEXT NOT NULL,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.auditoria (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario TEXT NOT NULL,
    rol TEXT NOT NULL,
    accion TEXT NOT NULL,
    detalle TEXT NOT NULL,
    servidor TEXT NOT NULL,
    exito SMALLINT NOT NULL CHECK (exito IN (0, 1)),
    creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE public.productos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.usuarios ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.operaciones ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.auditoria ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.productos, public.usuarios,
    public.operaciones, public.auditoria FROM anon, authenticated;
REVOKE ALL ON SEQUENCE public.auditoria_id_seq FROM anon, authenticated;

